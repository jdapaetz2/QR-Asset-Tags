#!/usr/bin/env node
/**
 * Engineering Phase D5.1 — export the email header logo from the brand artwork. docs/brand/BRAND.md names
 * mulemark-lockup.svg as the email header source; the wordmark is outline artwork and is never re-set from a font.
 *
 * Renders the lockup with sharp at three times its email display width, flattens it onto white (dark-mode mail clients
 * recolour a transparent ground, which would hide the iron wordmark; the email card behind it is white, so the glyph's
 * punched hole still shows what is behind it), and writes the PNG as base64 into the generated module
 * lib/notifications/email-logo.ts. Embedding it in source keeps the serverless bundle free of file tracing.
 *
 * Re-run after the lockup artwork changes:
 *   npm run brand:email-logo
 */
import { readFileSync, writeFileSync } from "node:fs";

import sharp from "sharp";

const SOURCE = "docs/brand/mulemark-lockup.svg";
const TARGET = "lib/notifications/email-logo.ts";
const DISPLAY_WIDTH = 200;
const SCALE = 3;

const { data, info } = await sharp(readFileSync(SOURCE), { density: 144 })
  .resize({ width: DISPLAY_WIDTH * SCALE })
  .flatten({ background: "#ffffff" })
  .png({ compressionLevel: 9, palette: true, colours: 64 })
  .toBuffer({ resolveWithObject: true });

const displayHeight = Math.round(info.height / SCALE);
const chunks = data.toString("base64").match(/.{1,100}/g) ?? [];

const source = `/**
 * GENERATED by scripts/brand/export-email-logo.mjs from ${SOURCE}. Do not edit by hand; run \`npm run brand:email-logo\`.
 *
 * Engineering Phase D5.1 — the Mulemark lockup for email headers: a ${info.width}×${info.height} PNG on white
 * (${data.byteLength} bytes), shown at ${DISPLAY_WIDTH}×${displayHeight} px and attached inline to every notification email.
 */
export const EMAIL_LOGO = {
  filename: "mulemark-logo.png",
  contentType: "image/png",
  contentId: "mm-logo@mulemark",
  width: ${DISPLAY_WIDTH},
  height: ${displayHeight},
  pixelWidth: ${info.width},
  pixelHeight: ${info.height},
  base64: [
${chunks.map((chunk) => `    "${chunk}",`).join("\n")}
  ].join(""),
} as const;
`;

writeFileSync(TARGET, source);
console.log(`[brand:email-logo] wrote ${TARGET}: ${info.width}×${info.height} PNG, ${data.byteLength} bytes`);
